let _ready = false;
async function ensureBirthdays() {
  if (_ready) return;
  try {
    await pool.query(`CREATE TABLE IF NOT EXISTS ticketsmodule_staff_birthdays (
      id SERIAL PRIMARY KEY,
      full_name VARCHAR(200) NOT NULL,
      birth_month SMALLINT NOT NULL,
      birth_day SMALLINT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT NOW()
    )`);
    await pool.query('CREATE UNIQUE INDEX IF NOT EXISTS uq_staff_bday ON ticketsmodule_staff_birthdays(full_name, birth_month, birth_day)');
    if (SEED.length) {
      const vals = [], params = [];
      SEED.forEach((b, i) => { const o = i * 3; vals.push(`($${o+1},$${o+2},$${o+3})`); params.push(b.name, b.m, b.d); });
      await pool.query(`INSERT INTO ticketsmodule_staff_birthdays (full_name, birth_month, birth_day) VALUES ${vals.join(',')} ON CONFLICT (full_name, birth_month, birth_day) DO NOTHING`, params);
    }
    _ready = true;
  } catch (e) { console.error('birthdays sync:', e.message); }
}
