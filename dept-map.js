// Может ли пользователь ЦУП комментировать сделку менеджера dealMgrId.
// userBid — Bitrix-ID пользователя (или null, если учётка не связана).
function canCommentDeal(user, dealMgrId, userBid) {
  if (!user) return false;
  if (user.role === 'admin') return true;                  // админ — любые сделки
  const bid = userBid != null ? parseInt(userBid, 10) : null;
  if (!bid) return false;                                   // не связан с Bitrix — только чтение
  const mgr = dealMgrId != null ? parseInt(dealMgrId, 10) : null;
  if (mgr && mgr === bid) return true;                      // своя сделка
  const myDept = EMPLOYEE_DEPT[bid];
  const dealDept = mgr ? EMPLOYEE_DEPT[mgr] : null;
  return !!(myDept && dealDept && myDept === dealDept);     // сделка своего отдела
}

module.exports = { EMPLOYEE_DEPT, canCommentDeal };
